"""Pure-math core of (constrained) REBEL (Gao et al. 2024, arXiv:2404.16767, Algorithm 1 / Eq. 1).

Fixed standardization (from the pi_0 calibration set, never recomputed):
    S~(x, y) = (S(x, y) - mu_S) / sigma_S                                  for every scorer S in {F, R, C}

Pairs: the G completions of a prompt are split into G/2 disjoint pairs by a FIXED randomized rule that
depends only on (policy seed, rollout batch index, prompt position) -- never on any score.

Regression target (per pair, constant for all optimizer steps on the rollout batch):
    z_t = (R~(y1) - R~(y2)) - lambda_t (C~(y1) - C~(y2))      constrained arms
    z_t =  F~(y1) - F~(y2)                                     scalar arm
Loss (the paper's 1/eta form, mean of squared residuals over pairs):
    L_t(theta) = mean_pairs [ ( ((l_theta(y1) - l_t(y1)) - (l_theta(y2) - l_t(y2))) / eta - z_t )^2 ]
with l(y) = SUM over completion tokens of log pi(y_k | x, y_<k) (sequence level, prompt/padding masked).
Exact minimization over all pairs recovers pi_{t+1}(y|x) proportional to pi_t(y|x) exp(eta [R~ - lambda C~]).

Dual (projected additive, once per rollout batch, after the primal steps of that batch):
    lambda_{t+1} = max(0, lambda_t + beta_dual (C_hat_t - d)),   C_hat_t = mean standardized cost of ALL
    rollouts generated by pi_t (the policy BEFORE this batch's primal update) -> the cost estimate lags the
    updated policy by one iteration. d is in standardized units (d = -0.5 <=> raw d = mu_C - 0.5 sigma_C).
"""
from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch


# --------------------------------------------------------------------------- standardization

def standardize(x: torch.Tensor, mu: float, sigma: float) -> torch.Tensor:
    if not (np.isfinite(sigma) and sigma > 0):
        raise ValueError(f"standardization needs a positive finite sigma, got {sigma}")
    return (x.detach().float() - float(mu)) / float(sigma)


def raw_threshold(mu: float, sigma: float, d_std: float) -> float:
    """Raw-unit threshold equivalent to the standardized constraint E[C~] <= d_std."""
    return float(mu) + float(d_std) * float(sigma)


# --------------------------------------------------------------------------- pairing

def pair_indices(n_prompts: int, group_size: int, seed: int, batch_index: int) -> List[Tuple[int, int]]:
    """Disjoint pairs of trajectory indices (prompt-major layout: prompt g owns g*G .. g*G+G-1).
    The permutation for prompt g is seeded by (seed, batch_index, g) only -> independent of rewards,
    reproducible across resumes, identical for all arms."""
    if group_size % 2 != 0:
        raise ValueError("group_size must be even to form disjoint pairs")
    pairs: List[Tuple[int, int]] = []
    for g in range(n_prompts):
        perm = np.random.default_rng([int(seed), int(batch_index), int(g), 7919]).permutation(group_size)
        for k in range(0, group_size, 2):
            pairs.append((g * group_size + int(perm[k]), g * group_size + int(perm[k + 1])))
    return pairs


# --------------------------------------------------------------------------- regression loss

def rebel_loss(lp_new_1: torch.Tensor, lp_new_2: torch.Tensor, lp_old_1: torch.Tensor, lp_old_2: torch.Tensor,
               target: torch.Tensor, eta: float) -> Dict[str, Any]:
    """Sequence-level SUMMED log-probs per pair member ([n_pairs] each). Only lp_new_* carry gradients.
    Returns the loss = mean over pairs of the squared residual (never the square of the mean)."""
    if eta <= 0:
        raise ValueError("eta must be positive")
    lp_old_1 = lp_old_1.detach().float(); lp_old_2 = lp_old_2.detach().float()
    target = target.detach().float()
    pred = ((lp_new_1.float() - lp_old_1) - (lp_new_2.float() - lp_old_2)) / float(eta)
    resid = pred - target
    loss = (resid ** 2).mean()
    with torch.no_grad():
        p, z = pred.detach(), target
        corr = float(torch.corrcoef(torch.stack([p, z]))[0, 1]) if p.numel() > 1 and p.std() > 0 and z.std() > 0 else float("nan")
        stats = {"loss_value": float(loss.detach()), "n_pairs": int(p.numel()), "pred_mean": float(p.mean()), "pred_std": float(p.std(unbiased=False)),
                 "target_mean": float(z.mean()), "target_std": float(z.std(unbiased=False)), "target_sq_mean": float((z ** 2).mean()),
                 "resid_abs_mean": float(resid.detach().abs().mean()), "pred_target_corr": corr,
                 "sign_agreement": float((torch.sign(p) == torch.sign(z)).float().mean())}
    return {"loss": loss, "residual": resid.detach(), "pred": pred.detach(), **stats}


# --------------------------------------------------------------------------- dual variable

@dataclass
class AdditiveDual:
    """lambda_{t+1} = max(0, lambda_t + beta (C_hat - d)); no EMA, no log parametrization, no cap."""
    d: float
    beta: float
    lam: float = 1.0
    project: bool = True
    n_updates: int = 0
    last_cost: Optional[float] = None

    def __post_init__(self) -> None:
        if self.lam < 0:
            raise ValueError("lambda_0 must be non-negative")

    @property
    def ema(self) -> Optional[float]:  # compatibility with GRPO-style monitoring (= last batch cost; no smoothing)
        return self.last_cost

    def update(self, c_hat: float) -> Dict[str, Any]:
        c_hat = float(c_hat)
        if not np.isfinite(c_hat):
            raise FloatingPointError(f"non-finite cost estimate {c_hat} in the dual update")
        lam_prev = self.lam
        violation = c_hat - self.d                       # > 0 : constraint violated -> lambda must increase
        unprojected = lam_prev + self.beta * violation
        self.lam = max(0.0, unprojected) if self.project else unprojected
        self.n_updates += 1
        self.last_cost = c_hat
        return {"lambda_prev": lam_prev, "lambda": self.lam, "lambda_unprojected": unprojected, "projected": bool(unprojected < 0.0),
                "violation": violation, "c_batch": c_hat, "c_ema": c_hat, "d": self.d,
                "log_lambda": math.log(self.lam) if self.lam > 0 else None}

    def state_dict(self) -> Dict[str, Any]:
        return {"d": self.d, "beta": self.beta, "lam": self.lam, "project": self.project, "n_updates": self.n_updates, "last_cost": self.last_cost}

    @classmethod
    def from_state_dict(cls, sd: Dict[str, Any]) -> "AdditiveDual":
        return cls(d=float(sd["d"]), beta=float(sd["beta"]), lam=float(sd["lam"]), project=bool(sd["project"]),
                   n_updates=int(sd["n_updates"]), last_cost=sd["last_cost"])


# --------------------------------------------------------------------------- reference-KL reward shaping (paper Eq. 22)

def kl_shaping(lp_t_sum: torch.Tensor, lp_0_sum: torch.Tensor, n_tokens: torch.Tensor, gamma: float, units: str = "token_mean") -> torch.Tensor:
    """gamma * (log pi_t(y|x) - log pi_0(y|x)) per response, to be SUBTRACTED from the reward before pairing.
    units = "sequence_sum" (the paper's Eq. 22, sum over tokens) or "token_mean" (divided by the response length: the per-token
    weighting GRPO's beta term uses). Detached constant; zero when gamma = 0."""
    d = (lp_t_sum.detach().float() - lp_0_sum.detach().float())
    if units == "token_mean":
        d = d / n_tokens.float().clamp(min=1.0)
    elif units != "sequence_sum":
        raise ValueError(f"unknown units {units!r}")
    return float(gamma) * d


# --------------------------------------------------------------------------- KL estimators (monitoring only)

def kl_stats(lp_p: Sequence[torch.Tensor], lp_q: Sequence[torch.Tensor]) -> Dict[str, float]:
    """Samples y ~ p (per-token log-probs ``lp_p``); ``lp_q`` = the same tokens under q.
    r = log q - log p.  k3 = exp(r) - r - 1 (non-negative, unbiased for KL(p||q) under p);  k1 = -r (unbiased, signed).
    Reports per-token means and the mean per-sequence SUM (sequence-level KL)."""
    if not len(lp_p):
        return {"kl_k3_token_mean": 0.0, "kl_k1_token_mean": 0.0, "kl_k3_seq_mean": 0.0, "kl_k3_token_max": 0.0, "n_tokens": 0, "finite": True}
    rs = [q.float() - p.float() for p, q in zip(lp_p, lp_q)]
    r = torch.cat(rs)
    k3 = torch.exp(r) - r - 1.0
    seq = torch.stack([(torch.exp(x) - x - 1.0).sum() for x in rs])
    return {"kl_k3_token_mean": float(k3.mean()), "kl_k1_token_mean": float((-r).mean()), "kl_k3_seq_mean": float(seq.mean()),
            "kl_k3_token_max": float(k3.max()), "n_tokens": int(r.numel()), "finite": bool(torch.isfinite(r).all())}


def exponential_tilt(pi_t: torch.Tensor, reward: torch.Tensor, eta: float) -> torch.Tensor:
    """Closed-form KL-regularized update on a finite action set: pi_{t+1} proportional to pi_t exp(eta r) (reference for tests)."""
    w = pi_t * torch.exp(float(eta) * reward)
    return w / w.sum()
