CONSTRAINED_ARMS = ("shared", "separate")


def is_constrained(arm: str) -> bool:
    return arm in CONSTRAINED_ARMS


def gen_seed(seed: int, batch_index: int) -> int:
    """Rollout sampling seed: a pure function of (policy seed, rollout batch index) -> resume-safe."""
    return int(seed) * 1_000_003 + int(batch_index)


def rng_states() -> Dict[str, Any]:
    st = {"python": random.getstate(), "numpy": np.random.get_state(), "torch_cpu": torch.get_rng_state()}
    if torch.cuda.is_available():
        st["torch_cuda"] = torch.cuda.get_rng_state_all()
    return st


def set_rng_states(st: Dict[str, Any]) -> None:
    random.setstate(st["python"])
    np.random.set_state(st["numpy"])
    torch.set_rng_state(st["torch_cpu"])
    if "torch_cuda" in st and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(st["torch_cuda"])


def device_memory(device: str) -> Dict[str, float]:
    if device.startswith("cuda"):
        return {"allocated_gb": torch.cuda.memory_allocated() / 2**30, "max_allocated_gb": torch.cuda.max_memory_allocated() / 2**30,
                "reserved_gb": torch.cuda.memory_reserved() / 2**30}
    if device == "mps":
        return {"allocated_gb": torch.mps.current_allocated_memory() / 2**30, "driver_gb": torch.mps.driver_allocated_memory() / 2**30}
    return {}


class GRPOTrainer:
    def __init__(self, cfg: Dict[str, Any]):
        self.cfg = cfg
        self.arm = cfg["arm"]
        self.constrained = is_constrained(self.arm)
        self.seed = int(cfg["seed"])
        if world_size() != 1:
            raise RuntimeError("single-process trainer: launch one process (model placement across GPUs via *_device options)")
        if int(cfg.get("prompt_epochs", 1)) != 1:
            raise ValueError("exactly ONE prompt epoch is pre-specified for all GRPO arms")
        self.device = pick_device(cfg.get("device", "auto"))
        self.ref_device = cfg.get("ref_device") or self.device
        self.scorer_device = cfg.get("scorer_device") or self.device
        self.precision = cfg["precision"]
        self.gen_precision = cfg.get("generation_precision") or self.precision  # fp32 only needed on MPS (bf16 sampling NaNs)
        self.run_dir = Path(cfg["runs_dir"]) / f"{cfg['run_name']}_seed{self.seed}"
        self.run_dir.mkdir(parents=True, exist_ok=True)
        self.gen = cfg["generation"]
        self.B, self.G = int(cfg["prompt_batch_size"]), int(cfg["group_size"])
        self.groups_per_mb = int(cfg["groups_per_minibatch"])
        self.micro = int(cfg.get("policy_micro_batch_size", self.G))
        self.n_gpus = torch.cuda.device_count() if torch.cuda.is_available() else 0

    # ------------------------------------------------------------------ setup
    def setup(self) -> None:
        cfg = self.cfg
        seed_everything(self.seed)
        self.tok = load_tokenizer(cfg["policy_model"])
        self.pad = self.tok.pad_token_id
        self.train_prompts = load_prompts(cfg["artifacts_dir"], "train")
        self.monitor_prompts = load_prompts(cfg["artifacts_dir"], "monitoring")
        self.order = prompt_order(len(self.train_prompts), self.seed)
        self.batches = rollout_batches(self.order, self.B)
        self.total_opt_steps = sum(math.ceil(len(b) / self.groups_per_mb) for b in self.batches)
        if cfg.get("schedule_total_batches"):   # pilots: define the LR schedule over the MAIN run's batch count (e.g. 566) on a smaller manifest
            self.total_opt_steps = int(cfg["schedule_total_batches"]) * math.ceil(self.B / self.groups_per_mb)
        if cfg.get("max_rollout_batches"):
            self.batches = self.batches[: int(cfg["max_rollout_batches"])]
        attn = cfg.get("attn_implementation")  # null -> transformers default (sdpa); "eager" is needed on Apple MPS for padded generation
        self.policy = load_model(cfg["policy_model"], self.device, torch.float32, bool(cfg["gradient_checkpointing"]), attn)
        self.ref = load_model(cfg["policy_model"], self.ref_device, torch.bfloat16 if self.precision == "bf16" else torch.float32,
                              attn_implementation=attn)
        self.ref.eval()
        for p in self.ref.parameters():
            p.requires_grad_(False)
        # The frozen scorer checkpoint(s) are the SAME for every policy seed of an arm: RM training seed
        # ``scorer_rm_seed`` (42), best-by-validation checkpoint. Paths must never depend on the policy seed.
        rm_seed = cfg.get("scorer_rm_seed")
        if rm_seed is not None:
            for k, pth in cfg["scorer_checkpoints"].items():
                if f"_seed{int(rm_seed)}/" not in str(pth) and "tiny" not in str(pth) and "pytest" not in str(pth):
                    raise ValueError(f"scorer checkpoint {k}={pth} is not the RM seed-{rm_seed} checkpoint required by scorer_rm_seed")
        self.scorers = FrozenScorers(self.arm, cfg["scorer_checkpoints"], self.scorer_device, self.precision,
                                     int(cfg.get("scorer_batch_size", 16)), self.gen["max_prompt_length"],
                                     self.gen["max_prompt_length"] + self.gen["max_completion_length"])
        self.dual: Optional[DualState] = None
        self.calibration = None
        if self.constrained:
            self.calibration = read_json(cfg["calibration_file"])
            if self.calibration["arm"] != self.arm:
                raise ValueError(f"calibration file is for arm {self.calibration['arm']!r}, run arm is {self.arm!r}")
            for k, fp in self.calibration["scorer_checkpoints"].items():
                mine = self.scorers.fingerprints.get(k, {})
                if fp.get("model.safetensors") != mine.get("model.safetensors") or fp.get("heads.pt") != mine.get("heads.pt"):
                    raise ValueError(f"calibrated d was computed with a different {k} checkpoint than the one loaded")
            self.dual = DualState(d=float(self.calibration["d"]), eta=float(cfg["dual_learning_rate"]),
                                  log_lambda=math.log(float(cfg.get("lambda_init", 1.0))), ema_decay=float(cfg.get("cost_ema_decay", 0.9)))
        self.optimizer = torch.optim.AdamW(self.policy.parameters(), lr=float(cfg["learning_rate"]),
                                           betas=(float(cfg["adam_beta1"]), float(cfg["adam_beta2"])), eps=float(cfg["adam_epsilon"]),
                                           weight_decay=float(cfg["weight_decay"]))
        self.scheduler, self.warmup_steps = build_scheduler(self.optimizer, cfg, self.total_opt_steps)
        self.state = {"next_batch_index": 0, "opt_step": 0, "n_prompts": 0, "n_trajectories": 0, "n_generated_tokens": 0,
                      "n_truncated": 0, "n_zero_variance_groups": 0, "n_groups": 0, "elapsed_s": 0.0, "n_dual_updates": 0}
        self.monitor_history: List[Dict[str, Any]] = []
        self.batch_log = open(self.run_dir / "rollout_batches.jsonl", "a", encoding="utf-8")
        write_json(self.run_dir / "config_resolved.json", {
            **{k: v for k, v in cfg.items() if not k.startswith("_")}, "device": self.device, "ref_device": self.ref_device,
            "scorer_device": self.scorer_device, "n_train_prompts": len(self.train_prompts), "n_rollout_batches": len(self.batches),
            "total_optimizer_steps": self.total_opt_steps, "warmup_steps": self.warmup_steps, "expected_trajectories": len(self.order) * self.G,
            "scorer_fingerprints": self.scorers.fingerprints, "calibration": self.calibration, "n_gpus": self.n_gpus,
            "policy_parameters": sum(p.numel() for p in self.policy.parameters()), "scorer_parameters": self.scorers.num_parameters()})
        log.info("arm=%s seed=%d prompts=%d batches=%d opt_steps=%d warmup=%d device=%s d=%s", self.arm, self.seed, len(self.train_prompts),
                 len(self.batches), self.total_opt_steps, self.warmup_steps, self.device, self.dual.d if self.dual else None)

    # ------------------------------------------------------------------ resume
    def resume_path(self) -> Path:
        return self.run_dir / "resume" / "latest.pt"

    def save_resume(self) -> None:
        path = self.resume_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".pt.tmp")
        torch.save({
            "policy": {k: v.detach().cpu().clone() for k, v in self.policy.state_dict().items()},
            "optimizer": self.optimizer.state_dict(), "scheduler": self.scheduler.state_dict(), "state": self.state,
            "dual": self.dual.state_dict() if self.dual else None, "rng": rng_states(), "monitor_history": self.monitor_history,
            "seed": self.seed, "arm": self.arm, "order_check": [self.order[0], self.order[-1], len(self.order)],
        }, tmp)
        os.replace(tmp, path)  # atomic: latest only
        log.info("resume state saved at batch %d (%s)", self.state["next_batch_index"], path)

    def load_resume(self) -> bool:
        path = self.resume_path()
        if not path.exists():
            return False
        ck = torch.load(path, map_location="cpu", weights_only=False)
        if ck["seed"] != self.seed or ck["arm"] != self.arm or ck["order_check"] != [self.order[0], self.order[-1], len(self.order)]:
            raise RuntimeError("resume state does not match this run's seed / arm / prompt order")
        self.policy.load_state_dict(ck["policy"])
        self.optimizer.load_state_dict(ck["optimizer"])
        self.scheduler.load_state_dict(ck["scheduler"])
        self.state = ck["state"]
        if self.dual is not None:
            self.dual = DualState.from_state_dict(ck["dual"])
            self.dual.eta = float(self.cfg["dual_learning_rate"])
        self.monitor_history = ck["monitor_history"]
        set_rng_states(ck["rng"])
        log.info("resumed from batch %d (opt_step %d, %d prompts done)", self.state["next_batch_index"], self.state["opt_step"], self.state["n_prompts"])
        return True

    # ------------------------------------------------------------------ one rollout batch
    def rollout_batch(self, batch_index: int, prompt_indices: List[int]) -> Dict[str, Any]:
        t0 = time.time()
        prompts = [self.train_prompts[i]["prompt"] for i in prompt_indices]
        lam_k = self.dual.lam if self.dual else None                     # 2. store lambda_k
        trajs = generate_completions(self.policy, self.tok, prompts, self.G, self.gen["max_prompt_length"],        # 1+3. pi_old = current weights
                                     self.gen["max_completion_length"], self.device, self.gen_precision, self.gen["temperature"],
                                     self.gen["top_p"], self.gen["repetition_penalty"], seed=gen_seed(self.seed, batch_index))
        t_gen = time.time() - t0
        sc = self.scorers.score(self.tok, [prompts[t["prompt_index"]] for t in trajs], [t["text"] for t in trajs])   # 4. scores
        if self.constrained:
            Z = lagrangian_scores(sc["reward"], sc["cost"], lam_k)                                                  # logged only (raw R - lambda C)
            adv_out = constrained_advantages(sc["reward"], sc["cost"], lam_k, self.G, float(self.cfg["advantage_eps"]))   # 5+6. A = A_R - lambda_k A_C
        else:
            Z = sc["scalar"].float()
            adv_out = group_advantages(Z, self.G, float(self.cfg["advantage_eps"]))                                 # 6. detached advantages
        adv = adv_out["advantages"]
        old_lp = batched_token_logprobs(self.policy, trajs, self.pad, self.micro, self.device, self.precision)       # pi_old log-probs (frozen for the batch)
        ref_lp = batched_token_logprobs(self.ref, trajs, self.pad, self.micro, self.ref_device, self.precision)      # pi_ref log-probs
        t_lp = time.time() - t0 - t_gen

        # 7. policy updates: minibatches of whole prompt groups, one optimizer step each, each trajectory once
        n_groups = len(prompts)
        group_ids = list(range(n_groups))
        agg = {"loss": 0.0, "kl": 0.0, "clip": 0.0, "ratio": 0.0, "n_tok": 0.0, "grad_norm": [], "steps": 0}
        self.policy.train()
        for mstart in range(0, n_groups, self.groups_per_mb):
            mb_groups = group_ids[mstart:mstart + self.groups_per_mb]
            mb_idx = [g * self.G + k for g in mb_groups for k in range(self.G)]
            n_mb = len(mb_idx)
            self.optimizer.zero_grad(set_to_none=True)
            for ustart in range(0, n_mb, self.micro):
                uidx = mb_idx[ustart:ustart + self.micro]
                utraj = [trajs[i] for i in uidx]
                b = collate_trajectories(utraj, self.pad)
                r = token_logprobs(self.policy, b, self.device, self.precision)
                T = r["token_logprobs"].shape[1]
                old = torch.zeros((len(uidx), T), dtype=torch.float32)
                ref = torch.zeros((len(uidx), T), dtype=torch.float32)
                for j, i in enumerate(uidx):
                    p = len(trajs[i]["prompt_ids"]); n = len(trajs[i]["completion_ids"])
                    old[j, p - 1: p - 1 + n] = old_lp[i]
                    ref[j, p - 1: p - 1 + n] = ref_lp[i]
                out = grpo_loss(r["token_logprobs"], old.to(self.device), ref.to(self.device), adv[uidx].to(self.device), r["mask"],
                                float(self.cfg["clip_epsilon"]), float(self.cfg["beta_kl"]))
                (out["loss"] * len(uidx) / n_mb).backward()   # mean over the minibatch's trajectories
                with torch.no_grad():
                    nt = float(out["n_tokens"])
                    agg["loss"] += float(out["loss"]) * len(uidx); agg["kl"] += float(out["kl_mean"]) * nt
                    agg["clip"] += float(out["clip_fraction"]) * nt; agg["ratio"] += float(out["ratio_mean"]) * nt; agg["n_tok"] += nt
            gn = torch.nn.utils.clip_grad_norm_(self.policy.parameters(), float(self.cfg["max_grad_norm"]))
            self.optimizer.step(); self.scheduler.step()
            self.state["opt_step"] += 1; agg["steps"] += 1; agg["grad_norm"].append(float(gn))
        self.policy.eval()
        self._last_trajs = trajs
        t_train = time.time() - t0 - t_gen - t_lp

        # 8+9. cost EMA and dual update (constrained arms), once per rollout batch, after the policy updates
        dual_rec = None
        if self.constrained:
            dual_rec = self.dual.update(float(sc["cost"].mean()))
            self.state["n_dual_updates"] += 1

        n_traj = len(trajs)
        n_tok = int(sum(t["n_completion_tokens"] for t in trajs))
        lens = np.array([t["n_completion_tokens"] for t in trajs])
        self.state["n_prompts"] += len(prompts); self.state["n_trajectories"] += n_traj; self.state["n_generated_tokens"] += n_tok
        self.state["n_truncated"] += int(sum(t["truncated"] for t in trajs)); self.state["n_groups"] += n_groups
        self.state["n_zero_variance_groups"] += adv_out["n_zero_variance_groups"]
        rec: Dict[str, Any] = {
            "batch_index": batch_index, "n_prompts": len(prompts), "n_trajectories": n_traj, "n_generated_tokens": n_tok,
            "completion_len_mean": float(lens.mean()), "completion_len_p50": float(np.median(lens)), "completion_len_p95": float(np.percentile(lens, 95)),
            "truncation_rate": float(np.mean([t["truncated"] for t in trajs])), "zero_variance_groups": adv_out["n_zero_variance_groups"],
            "optimizer_steps": agg["steps"], "opt_step_total": self.state["opt_step"], "lr": self.scheduler.get_last_lr()[0],
            "loss": agg["loss"] / n_traj, "kl_mean": agg["kl"] / max(agg["n_tok"], 1), "clip_fraction": agg["clip"] / max(agg["n_tok"], 1),
            "ratio_mean": agg["ratio"] / max(agg["n_tok"], 1), "grad_norm": agg["grad_norm"],
            "adv_abs_mean": float(adv.abs().mean()), "t_generate_s": t_gen, "t_logprobs_s": t_lp, "t_train_s": t_train,
            "t_batch_s": time.time() - t0, "memory": device_memory(self.device),
        }
        if self.constrained:
            c = sc["cost"].numpy(); rr = sc["reward"].numpy()
            rec.update({"lambda_used": lam_k, "lambda": dual_rec["lambda"], "log_lambda": dual_rec["log_lambda"], "cost_batch_mean": dual_rec["c_batch"],
                        "adv_reward_abs_mean": float(adv_out["adv_reward"].abs().mean()), "adv_cost_abs_mean": float(adv_out["adv_cost"].abs().mean()),
                        "zero_variance_reward_groups": adv_out["n_zero_variance_reward_groups"], "zero_variance_cost_groups": adv_out["n_zero_variance_cost_groups"],
                        "cost_ema": dual_rec["c_ema"], "d": dual_rec["d"], "violation_ema_minus_d": dual_rec["violation"],
                        "reward_mean": float(rr.mean()), "lagrangian_mean": float(Z.mean()), "cost_std": float(c.std()),
                        "cost_p5": float(np.percentile(c, 5)), "cost_median": float(np.median(c)), "cost_p95": float(np.percentile(c, 95))})
        else:
            s = sc["scalar"].numpy()
            rec.update({"scalar_reward_mean": float(s.mean()), "scalar_reward_std": float(s.std())})
        self.batch_log.write(json.dumps(rec) + "\n"); self.batch_log.flush()
        free_cache(self.device)  # release cached generation / logits blocks between rollout batches
        return rec

    # ------------------------------------------------------------------ monitoring (diagnostic only)
    @torch.no_grad()
    def monitor(self, tag: str) -> Dict[str, Any]:
        t0 = time.time()
        k_resp = int(self.cfg.get("monitor_responses_per_prompt", 4))
        gen_batch = int(self.cfg.get("monitor_gen_batch", 32))
        prompts = self.monitor_prompts
        trajs_all, prompt_texts = [], []
        for k in range(k_resp):
            for start in range(0, len(prompts), gen_batch):
                chunk = prompts[start:start + gen_batch]
                recs = generate_completions(self.policy, self.tok, [p["prompt"] for p in chunk], 1, self.gen["max_prompt_length"],
                                            self.gen["max_completion_length"], self.device, self.gen_precision, self.gen["temperature"],
                                            self.gen["top_p"], self.gen["repetition_penalty"], seed=MONITOR_GEN_SEEDS[k] * 100003 + start)
                trajs_all.extend(recs); prompt_texts.extend(p["prompt"] for p in chunk)
        sc = self.scorers.score(self.tok, prompt_texts, [t["text"] for t in trajs_all])
        pol = batched_token_logprobs(self.policy, trajs_all, self.pad, self.micro, self.device, self.precision)
        ref = batched_token_logprobs(self.ref, trajs_all, self.pad, self.micro, self.ref_device, self.precision)
        kl_tok = torch.cat([torch.exp(r - p) - (r - p) - 1.0 for p, r in zip(pol, ref)])
        lens = np.array([t["n_completion_tokens"] for t in trajs_all])
        m: Dict[str, Any] = {"tag": tag, "batch_index": self.state["next_batch_index"], "opt_step": self.state["opt_step"],
                             "n_prompts": len(prompts), "n_trajectories": len(trajs_all), "kl_mean": float(kl_tok.mean()),
                             "completion_len_mean": float(lens.mean()), "completion_len_p50": float(np.median(lens)),
                             "completion_len_p95": float(np.percentile(lens, 95)), "truncation_rate": float(np.mean([t["truncated"] for t in trajs_all])),
                             "seconds": time.time() - t0}
        if self.constrained:
            c = sc["cost"].numpy(); rr = sc["reward"].numpy()
            m.update({"reward_mean": float(rr.mean()), "cost_mean": float(c.mean()), "cost_std": float(c.std()), "d": self.dual.d,
                      "cost_minus_d": float(c.mean()) - self.dual.d, "lambda": self.dual.lam, "cost_ema": self.dual.ema})
        else:
            s = sc["scalar"].numpy()
            m.update({"scalar_reward_mean": float(s.mean()), "scalar_reward_std": float(s.std())})
        self.monitor_history.append(m)
        (self.run_dir / "monitor").mkdir(exist_ok=True)
        write_json(self.run_dir / "monitor" / f"{tag}.json", m)
        if self.cfg.get("monitor_save_samples", False):   # pilots: keep the monitoring text for the dev-prompt scoring (off by default)
            from .utils import write_jsonl
            write_jsonl(self.run_dir / "monitor" / f"{tag}_samples.jsonl",
                        ({"prompt": p, "response": t["text"], "n_completion_tokens": t["n_completion_tokens"], "truncated": t["truncated"]}
                         for p, t in zip(prompt_texts, trajs_all)))
        write_json(self.run_dir / "monitor_history.json", self.monitor_history)
        log.info("MONITOR %s: %s", tag, {k: (round(v, 4) if isinstance(v, float) else v) for k, v in m.items() if k not in ("tag",)})
        return m

    # ------------------------------------------------------------------ gate diagnostic (full-distribution sampling)
    @torch.no_grad()
    def diagnostic(self, tag: str, gates: Optional[Dict[str, float]] = None, n_samples: Optional[int] = None) -> Dict[str, Any]:
        """Fixed sample of monitoring prompts (one full-distribution response each, fixed seed): tail mass outside
        top-20, entropy, ASCII coherence, truncation, KL to pi_ref, finiteness of training records; writes
        diagnostic/<tag>.json and <tag>_samples.jsonl and evaluates the gates."""
        dcfg = self.cfg.get("diagnostic", {}) or {}
        n = int(n_samples or dcfg.get("n_samples", 32))
        prompts = self.monitor_prompts[:n]
        recs = []
        for start in range(0, len(prompts), 16):
            chunk = prompts[start:start + 16]
            recs.extend(generate_completions(self.policy, self.tok, [p["prompt"] for p in chunk], 1, self.gen["max_prompt_length"],
                                             self.gen["max_completion_length"], self.device, self.gen_precision, self.gen["temperature"],
                                             self.gen["top_p"], self.gen["repetition_penalty"], seed=int(dcfg.get("seed", 4242)) * 1000 + start))
        tm = tail_mass_and_entropy(self.policy, recs, self.pad, self.device, self.precision, k=20)
        pol = batched_token_logprobs(self.policy, recs, self.pad, self.micro, self.device, self.precision)
        ref = batched_token_logprobs(self.ref, recs, self.pad, self.micro, self.ref_device, self.precision)
        kl_tok = torch.cat([torch.exp(r - p) - (r - p) - 1.0 for p, r in zip(pol, ref)]) if recs else torch.zeros(1)
        texts = [r["text"] for r in recs]
        last_records = []
        try:
            with open(self.run_dir / "rollout_batches.jsonl", "r", encoding="utf-8") as f:
                last_records = [json.loads(l) for l in f.readlines()[-50:]]
        except FileNotFoundError:
            pass
        lens = np.array([r["n_completion_tokens"] for r in recs]) if recs else np.zeros(1)
        m: Dict[str, Any] = {
            "tag": tag, "batch_index": self.state["next_batch_index"], "opt_step": self.state["opt_step"], "n_samples": len(recs),
            "tail_mass": tm["tail_mass"], "entropy": tm["entropy"], "kl_mean": float(kl_tok.mean()), "kl_max_token": float(kl_tok.max()),
            "truncation_rate": float(np.mean([r["truncated"] for r in recs])) if recs else 0.0,
            "completion_len_mean": float(lens.mean()), "completion_len_p50": float(np.median(lens)), "completion_len_p95": float(np.percentile(lens, 95)),
            **ascii_stats(texts), "finite": bool(tm["finite"] and torch.isfinite(kl_tok).all() and records_finite(last_records)),
            "lambda": self.dual.lam if self.dual else None, "cost_ema": self.dual.ema if self.dual else None, "d": self.dual.d if self.dual else None,
        }
        m["gates"] = evaluate_gates(m, gates)
        (self.run_dir / "diagnostic").mkdir(exist_ok=True)
        write_json(self.run_dir / "diagnostic" / f"{tag}.json", m)
        from .utils import write_jsonl
        write_jsonl(self.run_dir / "diagnostic" / f"{tag}_samples.jsonl",
                    ({"prompt": p["prompt"], "prompt_hash": p["prompt_hash"], "response": r["text"], "n_completion_tokens": r["n_completion_tokens"],
                      "truncated": r["truncated"]} for p, r in zip(prompts, recs)))
        log.info("DIAGNOSTIC %s: passed=%s tail=%.4f entropy=%.3f kl=%.4f trunc=%.3f len=%.0f ascii=%.3f finite=%s | %s", tag, m["gates"]["passed"],
                 m["tail_mass"], m["entropy"], m["kl_mean"], m["truncation_rate"], m["completion_len_mean"], m["ascii_mean"], m["finite"],
                 {k: v["passed"] for k, v in m["gates"]["checks"].items()})
        self.policy.train()
        return m

    @torch.no_grad()
    def collapse_probe(self, trajs: List[Dict[str, Any]], rec: Dict[str, Any]) -> Dict[str, Any]:
        """Cheap in-training check on the current rollout batch (its trajectories are full-distribution samples)."""
        sub = trajs[: int(self.cfg.get("collapse_probe_trajectories", 32))]
        tm = tail_mass_and_entropy(self.policy, sub, self.pad, self.device, self.precision, k=20)
        m = {"batch_index": rec["batch_index"], "tail_mass": tm["tail_mass"], "entropy": tm["entropy"], "kl_mean": rec["kl_mean"],
             "truncation_rate": rec["truncation_rate"], **ascii_stats([t["text"] for t in trajs]),
             "finite": bool(tm["finite"] and records_finite([rec]))}
        m["collapse"] = collapse_check(m, self.cfg.get("collapse"))
        (self.run_dir / "diagnostic").mkdir(exist_ok=True)
        with open(self.run_dir / "diagnostic" / "collapse_probes.jsonl", "a", encoding="utf-8") as f:
            f.write(json.dumps(m) + "\n")
        self.policy.train()
        return m

    def save_intermediate(self, batch_index: int) -> None:
        """Extra bf16 policy checkpoint after ``batch_index`` rollout batches (``checkpoint_at_batches``); training continues.
        Marked ``intermediate`` so the final-epoch evaluation rules refuse it; the fixed-budget rule ``after_batches:N`` accepts it."""
        d = self.run_dir / "checkpoints" / f"batch_{batch_index:05d}"
        save_checkpoint(self.policy, self.tok, d, self.cfg.get("checkpoint_dtype", "bfloat16"),
                        {"algorithm": "grpo", "arm": self.arm, "seed": self.seed, "intermediate": True, "batch_index": batch_index, **self.state,
                         "lambda": self.dual.lam if self.dual else None, "d": self.dual.d if self.dual else None})
        log.info("intermediate checkpoint saved: %s", d)

    # ------------------------------------------------------------------ main loop
    def train(self) -> Dict[str, Any]:
        self.setup()
        resumed = self.load_resume() if self.cfg.get("resume", True) else False
        t_start = time.time() - self.state["elapsed_s"]
        if not resumed and self.cfg.get("monitor_at_start", True):
            self.monitor("start")
        eval_every, resume_every = int(self.cfg["eval_every_batches"]), int(self.cfg["resume_every_batches"])
        for bi in range(self.state["next_batch_index"], len(self.batches)):
            rec = self.rollout_batch(bi, self.batches[bi])
            self.state["next_batch_index"] = bi + 1
            self.state["elapsed_s"] = time.time() - t_start
            if (bi + 1) % int(self.cfg.get("log_every_batches", 1)) == 0:
                msg = {k: (round(v, 4) if isinstance(v, float) else v) for k, v in rec.items()
                       if k in ("batch_index", "loss", "kl_mean", "clip_fraction", "truncation_rate", "completion_len_mean", "scalar_reward_mean",
                                "reward_mean", "cost_batch_mean", "cost_ema", "d", "lambda", "violation_ema_minus_d", "zero_variance_groups", "t_batch_s")}
                log.info("batch %d/%d %s", bi + 1, len(self.batches), msg)
            if (bi + 1) % eval_every == 0 and (bi + 1) < len(self.batches):
                self.monitor(f"batch_{bi + 1:05d}")
            if (bi + 1) % resume_every == 0 and (bi + 1) < len(self.batches):
                self.save_resume()
            if (bi + 1) in {int(x) for x in (self.cfg.get("checkpoint_at_batches") or [])}:   # fixed-budget studies: explicit extra checkpoints
                self.save_intermediate(bi + 1)
            probe_every = int(self.cfg.get("collapse_check_every", 0) or 0)
            if probe_every and (bi + 1) % probe_every == 0 and (bi + 1) < len(self.batches) and not self.cfg.get("stop_after_batches"):
                pm = self.collapse_probe(self._last_trajs, rec)
                log.info("collapse probe batch %d: tail=%.4f kl=%.3f ascii=%.3f collapsed=%s", bi + 1, pm["tail_mass"], pm["kl_mean"], pm["ascii_mean"], pm["collapse"]["collapsed"])
                if pm["collapse"]["collapsed"]:
                    self.save_resume()
                    write_json(self.run_dir / "diagnostic" / f"collapse_batch_{bi + 1:05d}.json", pm)
                    log.error("POLICY COLLAPSE detected at batch %d: %s -- stopping this arm (exit 3)", bi + 1, pm["collapse"]["reasons"])
                    self.batch_log.close()
                    raise SystemExit(3)
            stop_after = int(self.cfg.get("stop_after_batches") or 0)
            if stop_after and (bi + 1) >= stop_after:
                self.state["elapsed_s"] = time.time() - t_start
                self.save_resume()
                m = self.diagnostic(f"batch_{bi + 1:05d}", self.cfg.get("diagnostic_gates"))
                self.batch_log.close()
                summary = {"run_dir": str(self.run_dir), "arm": self.arm, "seed": self.seed, "stopped_for_diagnostic": True,
                           "stop_after_batches": stop_after, **self.state, "diagnostic": m, "gates_passed": m["gates"]["passed"]}
                write_json(self.run_dir / "diagnostic_summary.json", summary)
                log.info("stopped after %d batches for the gate diagnostic: gates_passed=%s (resume state saved; no final checkpoint written)",
                         stop_after, m["gates"]["passed"])
                return summary
        self.state["elapsed_s"] = time.time() - t_start
        final = self.monitor("final")
        final_dir = self.run_dir / "checkpoints" / "final"
        save_checkpoint(self.policy, self.tok, final_dir, self.cfg.get("checkpoint_dtype", "bfloat16"),
                        {"arm": self.arm, "seed": self.seed, "opt_step": self.state["opt_step"], "prompt_epochs": 1, **self.state})
        self.save_resume()
        summary = {
            "run_dir": str(self.run_dir), "arm": self.arm, "seed": self.seed, "policy_model": self.cfg["policy_model"],
            "n_train_prompts": len(self.train_prompts), "n_rollout_batches": len(self.batches), **self.state,
            "truncation_rate": self.state["n_truncated"] / max(1, self.state["n_trajectories"]),
            "wallclock_s": self.state["elapsed_s"], "gpu_hours": self.state["elapsed_s"] / 3600.0 * max(self.n_gpus, 1) if self.n_gpus else None,
            "n_gpus": self.n_gpus, "final_checkpoint": str(final_dir), "final_monitor": final, "d": self.dual.d if self.dual else None,
            "final_lambda": self.dual.lam if self.dual else None, "memory": device_memory(self.device), "resumed": resumed,
        }
        write_json(self.run_dir / "train_summary.json", summary)
        self.batch_log.close()
        log.info("done: %s", {k: v for k, v in summary.items() if k in ("n_prompts", "n_trajectories", "n_generated_tokens", "opt_step", "wallclock_s", "truncation_rate", "final_lambda")})
        return summary


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--set", nargs="*", default=[])
    args = ap.parse_args(argv)
    cfg = load_config(args.config, args.set)
    if args.seed is not None:
        cfg["seed"] = args.seed
    summary = GRPOTrainer(cfg).train()
    if summary.get("stopped_for_diagnostic") and not summary.get("gates_passed"):
        raise SystemExit(2)  # gate failed: dependent Slurm jobs (afterok) will not run


if __name__ == "__main__":
    main()
