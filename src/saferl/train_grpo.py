"""(Constrained) GRPO policy training for the reward-model arms.

Arms:  scalar   -> ordinary GRPO on the frozen scalar RM F
       shared   -> constrained GRPO with R, C from the frozen shared two-head model
       separate -> constrained GRPO with R, C from two frozen independent models

One prompt epoch over the fixed training-prompt manifest (seed-dependent order). Per rollout batch
(B prompts x G completions, generated by the current weights = pi_old): score -> Z = R - lambda C
(or F) -> detached group advantages -> minibatches of whole prompt groups (one optimizer step each,
every trajectory used exactly once, no inner epochs) -> cost EMA + dual update (constrained arms).
Reference KL uses the frozen original checkpoint pi_ref (distinct from pi_old).
"""
